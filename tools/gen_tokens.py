"""Generate ui/css/tokens.css from the møušn design system's tokens.json (colours per theme, type, spacing, shapes)."""
import json
from pathlib import Path

ui = Path(__file__).resolve().parent.parent / "edic" / "ui"
t = json.loads((ui / "design" / "tokens.json").read_text())

themes = [x["id"] for x in t["color"]["themes"]]
primary = themes[0]
blocks = {th: [] for th in themes}
for tok in t["color"]["tokens"]:
    for th in themes:
        v = tok["value"].get(th) or tok["value"][primary]
        blocks[th].append(f"  --{tok['name']}: {v};")

common = []
for fam, css in t["type"]["families"].items():
    common.append(f"  --font-{fam}: {css};")
for key in ("spacing", "radius", "cut", "shadow", "stroke"):
    for tok in t.get(key, {}).get("tokens", []):
        common.append(f"  --{tok['name']}: {tok['value']};")

out = ["/* generated by tools/gen_tokens.py from design/tokens.json - do not edit */",
       ":root,\n:root[data-theme=\"%s\"] {\n  color-scheme: dark;\n%s\n%s\n}" % (primary, "\n".join(blocks[primary]), "\n".join(common))]
for th in themes[1:]:
    out.append(":root[data-theme=\"%s\"] {\n  color-scheme: light;\n%s\n}" % (th, "\n".join(blocks[th])))
(ui / "css" / "tokens.css").write_text("\n".join(out) + "\n")
print("wrote tokens.css:", len(t["color"]["tokens"]), "colours")
